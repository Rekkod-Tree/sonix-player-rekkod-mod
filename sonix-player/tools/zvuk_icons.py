#!/usr/bin/env python3
"""Draws the Zvuk tile and badge and writes them as LVGL images.

    python3 tools/zvuk_icons.py

writes assets/icons/zvuk.png, assets/icons/zvuk-badge.png and
src/gui/streaming/zvukicons.c (inside #ifdef SONIX_ZVUK, so a build without
the service carries none of it). A file of its own rather than more entries in
svg_to_lvgl.py / icons.c: the service is fork-only and behind a build flag.

The tile uses the approved prototype line glyph. The separately drawn badge
over playing artwork is retained; neither is the service's official logo.
"""
import os
from PIL import Image, ImageDraw
import svg_to_lvgl as gen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, "assets", "icons")
OUT_C = os.path.join(ROOT, "src", "gui", "streaming", "zvukicons.c")

S = 4  # supersampling


def waves(d, cx, cy, r, width, fill):
    # A dot and three arcs opening to the right: sound going out.
    d.ellipse((cx - r * 0.36, cy - r * 0.36, cx + r * 0.36, cy + r * 0.36), fill=fill)
    for k in (1, 2, 3):
        rr = r * (0.35 + 0.75 * k)
        d.arc((cx - rr, cy - rr, cx + rr, cy + rr), start=-48, end=48, fill=fill, width=int(width))


def badge(size=52):
    n = 236 * S
    im = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.ellipse((0, 0, n - 1, n - 1), fill=(255, 255, 255, 255))
    m = int(n * 0.06)
    d.ellipse((m, m, n - 1 - m, n - 1 - m), fill=(124, 58, 237, 255))
    waves(d, n * 0.30, n * 0.5, n * 0.135, n * 0.052, (255, 255, 255, 255))
    return im.resize((size, size), Image.LANCZOS)


def c_image(name, im):
    raw = im.tobytes()
    out = bytearray()
    for i in range(0, len(raw), 4):
        out += bytes((raw[i + 2], raw[i + 1], raw[i], raw[i + 3]))  # LVGL ARGB8888 is BGRA in memory
    lines = []
    for i in range(0, len(out), 16):
        lines.append("\t" + ", ".join("0x%02x" % b for b in out[i:i + 16]) + ",")
    w, h = im.size
    return ("static const uint8_t %s_data[] = {\n%s\n};\n\n"
            "const lv_image_dsc_t %s = {\n\t.header = {\n\t\t.magic = LV_IMAGE_HEADER_MAGIC,\n"
            "\t\t.cf = LV_COLOR_FORMAT_ARGB8888,\n\t\t.w = %d,\n\t\t.h = %d,\n\t\t.stride = %d,\n\t},\n"
            "\t.data_size = sizeof(%s_data),\n\t.data = %s_data,\n};\n\n") % (
        name, "\n".join(lines), name, w, h, w * 4, name, name)


def main():
    data, width, height = gen.render(os.path.join(ICONS, "ui3-wave.svg"), 34)
    t = Image.frombytes("RGBA", (width, height), data, "raw", "BGRA")
    b = badge()
    t.save(os.path.join(ICONS, "zvuk.png"))
    b.save(os.path.join(ICONS, "zvuk-badge.png"))
    with open(OUT_C, "w") as f:
        f.write("// Generated by tools/zvuk_icons.py -- do not edit.\n#ifdef SONIX_ZVUK\n\n"
                "#include \"lvgl/lvgl.h\"\n\n#include \"src/gui/streaming/zvukpage.h\"\n\n")
        f.write("// The prototype's line glyph, matching the other 34px service tiles.\n")
        f.write(c_image("icon_menu_zvuk", t))
        f.write("// The mark over the artwork while a Zvuk track plays, as the other services' (52 px).\n")
        f.write(c_image("icon_zvuk_badge", b))
        f.write("#endif /* SONIX_ZVUK */\n")
    print("wrote", OUT_C)


if __name__ == "__main__":
    main()
